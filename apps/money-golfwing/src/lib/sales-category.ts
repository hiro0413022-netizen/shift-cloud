/**
 * 区分の表記ゆれを寄せる。
 *   「月会費」はファイン実績（口座振替）の予約語。窓口で受けた分は必ず「月会費(窓口)」へ
 *     （「月会費」で入ると月会費予測が自動停止して売上から約370万円消える・2026-09-29の実障害）
 *   「参加費」は過去台帳に4件だけある表記ゆれ。「参加料」へ寄せる
 */
export function normalizeSalesCategory(c: string): string {
  const s = String(c ?? "").trim();
  if (s === "月会費") return "月会費(窓口)";
  if (s === "参加費") return "参加料";
  return s;
}
