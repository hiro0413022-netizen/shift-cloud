-- ============================================================
-- 0137 体験予約に生年月日を持たせる（#190）
--
-- ユーザー指示（2026-09-01）「体験予約時に生年月日を入れるようにしてください、ここは必須」。
--
-- なぜ体験の時点で要るか:
--   体験のあと入会される方は、店頭で会員申込書にもう一度 生年月日 を書いている。
--   受付台帳（mbr_guests）にも生年月日の欄はあるのに、Web体験予約からは一度も入っていなかった
--   ＝年代別の集客分析もできない状態だった。予約のときにいただけば、来店時は確認だけで済む。
--
-- ⚠ NOT NULL にはしない。
--   ・既存の申込には値が無い（過去分を捏造しない）
--   ・スタッフが電話で受けて後から埋める入口（member-os /trials）が残っている
--   必須は「お客様が自分で予約する入口」で担保する（画面＋サーバーの両方・birth-date.ts）。
-- ============================================================

alter table mbr_trial_requests add column if not exists birth_date date;

comment on column mbr_trial_requests.birth_date is
  '生年月日。Web体験予約では必須（画面とAPIの両方で検証）。受付台帳 mbr_guests.birth_date へ引き継ぐ。';
